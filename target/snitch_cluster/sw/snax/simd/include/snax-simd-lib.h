// Driver for the standalone SIMD block (<cluster>_simd) on the four-engine
// cluster: hart 1's vector engine.
//
// THIS IS NOT A DMA. The first version of this header was a direct
// transliteration of snax-xdma-lib -- `memcpy_nd(src, dst, ...)` with thirteen
// positional arguments, `spatial_stride`, `enabled_byte_dst` -- which described
// a transfer that happens to compute something on the way. That is backwards.
// The block reads a stream, applies a chain of operators to it, and writes a
// stream; the addresses and strides are the *shape of the iteration space*, not
// a transfer descriptor. A copy is just the degenerate case with no operator.
//
// So the interface is three nouns:
//
//   snax_simd_shape_t   what to sweep -- base, lane layout, nested bounds/strides
//   snax_simd_op_t      what to compute -- an operator and its configuration
//   a task              = input shape + operator chain -> output shape
//
// and the verbs are configure / launch / wait, or `run` for all three:
//
//   snax_simd_shape_t in, out;
//   snax_simd_op_t    op;
//   snax_simd_shape_flat(&in,  x, beats);
//   snax_simd_shape_flat(&out, y, beats);
//   snax_simd_op_map(&op, SIMD_EXT_STREAMMAP, SIMD_FUNC_EXP,
//                    SIMD_F32_ONE, snax_simd_f32_neg(max_bits));
//   snax_simd_run(&in, &out, &op, 1);
//
// The input and output shapes are programmed independently ON PURPOSE, and this
// is the thing a DMA framing hides: the operator chain decides how many beats
// come out. A reduce turns N beats into 1 (or N+1 in tap mode); a quantiser
// turns N into N/2. The caller states both shapes because only it knows the
// chain. `snax_simd_out_beats()` computes the common cases.
//
// Everything cross-cluster is absent: no multicast, no remote destination, no
// chained transfer, no AXI. Every pointer is a local TCDM address.

#pragma once
#include <stdbool.h>
#include "snrt.h"
#include "stdint.h"

// CSR map, generated by snax.simd.SimdTopGen from the active cluster cfg.
#include "snax-simd-addr.h"

// ============================================================== capability gate
//
// The generated header names every extension the cfg built, and until it carried
// capabilities it could not say what any of them DOES. That gap is not cosmetic:
// an operator's func/op CSR is a runtime select over the set that was elaborated,
// and selecting outside that set does not fault. Ask StreamMap for RSQRT on a
// build without it and you get the LINEAR result -- a well-formed tensor of wrong
// numbers, with nothing reported anywhere.
//
// So the ops below are defined only when the hardware has them, and otherwise
// expand to an identifier that does not exist. Using one then fails AT THE USE
// SITE, with the missing capability spelled out in the compiler's message,
// instead of at run time with plausible output. A kernel that wants a nicer
// message still gates explicitly, but it can no longer forget to.
#if !defined(SIMD_EXT_CAPS)
#error \
    "snax-simd-addr.h predates the capability macros -- it cannot say which ops the SIMD block built, and an absent op returns another op's answer instead of faulting. Regenerate it: make sw-snax-gen CFG_OVERRIDE=<your cfg>"
#endif

// Expand to VALUE when CAP is defined, otherwise to an undeclared identifier
// naming what is missing. The two-step expansion is needed so NAME/CAP paste
// after their own macro arguments are substituted.
#define SIMD_CAP_GLUE_(a, b) a##b
#define SIMD_CAP_MISSING_(name) SIMD_CAP_GLUE_(SIMD_NOT_BUILT_ON_THIS_CLUSTER_, name)

// Base of this hart's SNAX CSR window. Same value as the xDMA's: csrw_ss/csrr_ss
// address the accelerator attached to THIS hart, and the two blocks sit on
// different harts, so there is no conflict.
#define SIMD_CFG_ADDR 960

// Bytes moved per beat, and bytes per lane within a beat.
#define SIMD_BEAT_BYTES SIMD_WIDTH
#define SIMD_LANE_BYTES (SIMD_WIDTH / SIMD_SPATIAL_CHAN)

// Deepest nested sweep the hardware supports, and the widest operator CSR block.
#define SIMD_MAX_DIM SIMD_SRC_TEMP_DIM
#define SIMD_MAX_OP_CSR 4

// always_inline so a compile-time-constant `addr` propagates into the
// csrr_ss/csrw_ss switch and constant-folds to a single direct csrr/csrw <imm>.
// Without it every CSR access pays a jump-table load from L2 plus an indirect
// jump -- which measured as the dominant cost of xDMA CSR configuration.
__attribute__((always_inline)) static inline uint32_t snax_read_simd_cfg_reg(
    uint32_t addr) {
    return csrr_ss(SIMD_CFG_ADDR + addr);
}
__attribute__((always_inline)) static inline void snax_write_simd_cfg_reg(
    uint32_t addr, uint32_t value) {
    csrw_ss(SIMD_CFG_ADDR + addr, value);
}

// ============================================================== shapes

// The iteration space of one side of a task.
//
// `bound`/`stride` are the nested loops, innermost first, in BEATS and BYTES
// respectively. `lane_stride` is the distance between adjacent lanes inside one
// beat -- SIMD_LANE_BYTES for contiguous data, something else for a strided
// gather. `lane_mask` selects participating lanes; `byte_mask` (output only)
// selects which bytes of each word are written.
typedef struct {
    void* base;  // must be SIMD_BEAT_BYTES aligned
    uint32_t lane_stride;
    uint32_t lane_mask;
    uint32_t byte_mask;
    uint32_t dim;
    uint32_t bound[SIMD_MAX_DIM];
    uint32_t stride[SIMD_MAX_DIM];
} snax_simd_shape_t;

// Constructors fill a caller-owned struct rather than returning one: a 60-byte
// by-value return lowers to a memcpy() call, and this is a freestanding runtime
// with no libc.

// `beats` consecutive beats from `base`.
void snax_simd_shape_flat(snax_simd_shape_t* s, void* base, uint32_t beats);

// `rows` rows of `beats_per_row` beats each, rows `row_stride` bytes apart.
// This is the shape a row-wise reduction sweeps.
void snax_simd_shape_rows(snax_simd_shape_t* s, void* base, uint32_t rows,
                          uint32_t beats_per_row, uint32_t row_stride);

// One beat, presented `beats` times. Stride 0 drives the reader's repeat path,
// which is how a per-row scalar is broadcast against a full row without
// materialising it.
// A 2-D sweep with strides given outright, innermost first, in BYTES. The two
// patterns the rows/flat helpers cannot express both live here:
//   stride0 == 0                 re-present one beat bound0 times (broadcast)
//   bound0 == 2, stride0 == d    interleave two operand streams d apart, which
//                                is how a 2-operand StreamElementwise is fed
// `d` must be POSITIVE: the AGU stride is unsigned, so a second operand placed
// below the first wraps the address, reads outside TCDM and writes X while the
// task still reports complete.
void snax_simd_shape_2d(snax_simd_shape_t* s, void* base, uint32_t bound0,
                        uint32_t stride0, uint32_t bound1, uint32_t stride1);

void snax_simd_shape_broadcast(snax_simd_shape_t* s, void* base,
                               uint32_t beats);

// Total beats a shape sweeps (the product of its bounds).
uint32_t snax_simd_shape_beats(const snax_simd_shape_t* s);

// ============================================================== operators

// Operator ids come from the generated header as SIMD_EXT_<NAME>; which ones
// exist depends on the cluster cfg.

// StreamMap: out = func(a * x + b), elementwise. csr(2) bits[1:0] select func.
//
// LINEAR is always built -- it is the affine itself, with no activation after it
// -- so only the activations are gated. The gates key off the UNSUFFIXED
// extension name, which the generator emits when the cfg holds exactly one
// StreamMap; a cfg with two names them _0/_1 and nothing here would match, which
// is why each gate first checks that the extension it is talking about exists.
#define SIMD_FUNC_LINEAR 0u
#if !defined(SIMD_EXT_STREAMMAP) || defined(SIMD_EXT_STREAMMAP_HAS_EXP)
#define SIMD_FUNC_EXP 1u
#else
#define SIMD_FUNC_EXP SIMD_CAP_MISSING_(STREAMMAP_EXP)
#endif
#if !defined(SIMD_EXT_STREAMMAP) || defined(SIMD_EXT_STREAMMAP_HAS_SILU)
#define SIMD_FUNC_SILU 2u
#else
#define SIMD_FUNC_SILU SIMD_CAP_MISSING_(STREAMMAP_SILU)
#endif
// out = 1/sqrt(a*x + b), for the per-row normalisations. `a` is where the division by the
// row length goes: a reduce emits SUM(x^2) and rmsnorm wants 1/sqrt(SUM/D), so a = 1/D and
// b = 0 -- and rather than costing a pass, this REPLACES the identity multiply on the
// broadcast pass that a per-row scalar already needs. Total: a non-positive or non-finite
// input gives 0, so an all-zero row normalises to zero instead of poisoning itself with
// +Inf. Accurate to 1 FP16 ULP, which is better than the core's integer sqrt+reciprocal.
#if !defined(SIMD_EXT_STREAMMAP) || defined(SIMD_EXT_STREAMMAP_HAS_RSQRT)
#define SIMD_FUNC_RSQRT 3u
#else
#define SIMD_FUNC_RSQRT SIMD_CAP_MISSING_(STREAMMAP_RSQRT)
#endif

// StreamReduce: fold a row of `operand_beats` down to one scalar beat.
//
// ADD and SUMSQ are not two build options: one fused multiply-add serves both and
// the op CSR picks the multiplicand, so a cfg listing only "FMA_FP16" still has
// them. The generated capabilities already say so -- they are the RUNTIME opcode
// set, expanded from the cfg's op list by the same function the datapath builds
// itself from, so these gates cannot disagree with the hardware.
#if !defined(SIMD_EXT_STREAMREDUCE) || defined(SIMD_EXT_STREAMREDUCE_HAS_MAX)
#define SIMD_RED_MAX 0u
#else
#define SIMD_RED_MAX SIMD_CAP_MISSING_(STREAMREDUCE_MAX)
#endif
#if !defined(SIMD_EXT_STREAMREDUCE) || defined(SIMD_EXT_STREAMREDUCE_HAS_ADD)
#define SIMD_RED_ADD 1u
#else
#define SIMD_RED_ADD SIMD_CAP_MISSING_(STREAMREDUCE_ADD)
#endif
#if !defined(SIMD_EXT_STREAMREDUCE) || defined(SIMD_EXT_STREAMREDUCE_HAS_SUMSQ)
#define SIMD_RED_SUMSQ 2u
#else
#define SIMD_RED_SUMSQ SIMD_CAP_MISSING_(STREAMREDUCE_SUMSQ)
#endif
// Pass the row through AND emit the scalar as a trailing beat, so one task
// yields both a transformed row and its reduction: N beats in, N+1 out.
#define SIMD_RED_TAP 0x100u
// Emit the scalar as FP32 rather than narrowing to the transport grid -- needed
// when the sum would overflow FP16.
#define SIMD_RED_FP32OUT 0x200u

// Emit the per-lane partials as one beat -- the reduction ACROSS beats -- instead
// of folding them to a scalar.
//
// The fold, its treeBuf serialisation and the scalar drain all exist to turn the
// lane partials into ONE number, and they are what makes a short row expensive:
// a 2-beat row costs ~40 cycles on the folding path, nearly all of it bubble.
// The partials are already the across-beat reduction, computed for free in the
// accumulator as the row streams past. Orient the data so the axis you want to
// reduce runs along BEATS and this returns exactly what you want, with no fold
// at all -- one output beat per row, `operandCount` beats in.
//
// For FlashAttention that means storing the score tile transposed: one lane is
// one query row, so a LANEWISE MAX over the key beats IS rowmax.
#define SIMD_RED_LANEWISE 0x400u

// Fp16ToInt8: pass every (tailPeriod+1)'th input beat through UNQUANTISED, where
// tailPeriod is the number of data beats in a row. csr(1); 0 disables it.
//
// This is what lets a StreamReduce TAP pass also narrow its output. TAP emits the
// row and then the row's reduction as a trailing beat, and the quantiser sits
// downstream of the reduce, so without this the scalar would be narrowed along
// with the data -- and a pass that produces both a tile and its statistic could
// not quantise the tile. The tile then has to be written in FP16 and read back a
// second time by a quantise-only task, which is a whole extra pass over it.
//
// tailPeriod must be a multiple of 2 (the FP16->INT8 pack ratio), so the pack the
// tail interrupts is always complete.
//
// This one is a BUILD-TIME feature, not a runtime select: without it the quantiser
// has one user CSR instead of two, so the tailPeriod write does not merely select
// nothing -- it lands past the end of this extension's CSR block, on whatever the
// generator placed next. Hence the gate, and hence it is the caller's second CSR
// word that disappears with it (see SIMD_EXT_FP16TOINT8_CSR_NUM).
#if !defined(SIMD_EXT_FP16TOINT8) || defined(SIMD_EXT_FP16TOINT8_HAS_TAILPASSTHROUGH)
#define SIMD_QUANT_TAIL(beats) ((uint32_t)(beats))
#else
#define SIMD_QUANT_TAIL(beats) SIMD_CAP_MISSING_(FP16TOINT8_TAILPASSTHROUGH)
#endif

// StreamElementwise: combine `operand_beats` interleaved operands into one.
//
// NOT gated, deliberately, and this is the one place the scheme does not reach.
// The chain holds TWO elementwise instances (pre-map and post-map) and these
// constants are the shared encoding, not a property of either; the question a
// kernel actually needs answered is "may THIS instance do MUL?", which a single
// macro cannot express. Gate at the call site instead, on the instance's own
// capability:
//
//     #if !defined(SIMD_EXT_STREAMELEMENTWISE_0_HAS_ADD)
//     #error "the pre-map elementwise on this cluster cannot add"
//     #endif
//
// As with StreamReduce, one fused FMA build op provides both MUL and ADD, so a
// cfg listing only "FMA_FP16" still reports both capabilities.
#define SIMD_EW_MUL 0u
#define SIMD_EW_ADD 1u

// Latch the FIRST beat of the task as operand B and combine every later beat
// against it, instead of taking both operands from the stream.
//
// Use with operandCount = 1, so each beat is its own row. Beat 0 seeds the latch
// and emits NOTHING; beats 1..N emit op(B, beat). So the task consumes 1 + N
// beats and produces N, the seed beat must sit IMMEDIATELY BELOW the data (the
// reader is one flat sweep and the seed is simply its first beat), and the
// writer descriptor covers exactly the data -- do not aim it one beat early.
// (It used to pass the seed through as a junk beat; the RTL suppresses it now,
// which is also what lets a sticky elementwise sit mid-chain without a
// downstream Reduce folding the junk in.)
//
// Without this a broadcast operand has to be physically replicated once per data
// beat -- a whole extra pass to write it and a doubled read stream to consume
// it -- and the AGU cannot avoid that, because one affine address stream cannot
// hold one operand's address fixed while the other walks.
#define SIMD_EW_STICKY_B 0x100u

typedef struct {
    uint8_t id;
    uint8_t csr_num;
    uint32_t csr[SIMD_MAX_OP_CSR];
} snax_simd_op_t;

// out = func(a * x + b). `a` and `b` are FP32 BIT PATTERNS -- see the note on
// floats above; SIMD_F32_ONE and snax_simd_f32_from_f16() cover most cases.
void snax_simd_op_map(snax_simd_op_t* op, uint8_t ext, uint32_t func,
                      uint32_t a_bits, uint32_t b_bits);

// Fold `operand_beats` beats into one scalar beat. `mode` is one of
// SIMD_RED_* optionally OR-ed with SIMD_RED_TAP / SIMD_RED_FP32OUT.
void snax_simd_op_reduce(snax_simd_op_t* op, uint8_t ext, uint32_t mode,
                         uint32_t operand_beats);

// Combine `operand_beats` interleaved operands elementwise.
void snax_simd_op_elementwise(snax_simd_op_t* op, uint8_t ext, uint32_t mode,
                              uint32_t operand_beats);

// FP16 -> INT8 quantisation by `inv_scale` (FP32 bits). Halves the beat count.
void snax_simd_op_quantise(snax_simd_op_t* op, uint8_t ext,
                           uint32_t inv_scale_bits);

// Any operator, given its raw CSR words -- the escape hatch for an extension
// this header does not model yet.
void snax_simd_op_raw(snax_simd_op_t* op, uint8_t ext, const uint32_t* csr,
                      uint32_t csr_num);

// NO `float` ANYWHERE IN THIS API, DELIBERATELY.
//
// The cores that drive the SIMD block are rv32ima -- integer only, no FPU. A
// `float` parameter compiles to an FP instruction and traps with an illegal
// instruction the moment the kernel runs. (Found exactly that way: `fmv.w.x`,
// opcode 0xf00005d3, on hart 1.) The operator CSRs take FP32 BIT PATTERNS, and
// the kernels already build those with integer arithmetic, so the API takes
// bits too.

#define SIMD_F32_ZERO 0x00000000u
#define SIMD_F32_ONE 0x3F800000u
#define SIMD_F32_NEG_ONE 0xBF800000u

// Flip the sign of an FP32 bit pattern -- integer-only, as the kernels do it.
static inline uint32_t snax_simd_f32_neg(uint32_t bits) {
    return bits ^ 0x80000000u;
}

// Widen an FP16 bit pattern to FP32 bits. Pure integer: the per-row scalars a
// reduction produces come back as FP16 and usually need widening before they
// can be fed to the next operator's `a`/`b`.
static inline uint32_t snax_simd_f32_from_f16(uint16_t h) {
    uint32_t sign = (uint32_t)(h >> 15) & 0x1u;
    uint32_t exp = (uint32_t)(h >> 10) & 0x1Fu;
    uint32_t mant = (uint32_t)(h & 0x3FFu);
    if (exp == 0) {
        if (mant == 0) return sign << 31;  // +-0
        int shift = 0;
        while ((mant & 0x400u) == 0) {
            mant <<= 1;
            shift++;
        }
        mant &= 0x3FFu;
        exp = 127 - 15 - shift + 1;
        return (sign << 31) | (exp << 23) | (mant << 13);
    }
    if (exp == 0x1F) return (sign << 31) | 0x7F800000u | (mant << 13);
    return (sign << 31) | ((exp - 15 + 127) << 23) | (mant << 13);
}

// ============================================================== tasks

// Program a task: sweep `in`, apply `ops` in order, write `out`. Does not
// launch. Returns 0, or negative on a shape/operator error.
int32_t snax_simd_configure(const snax_simd_shape_t* in,
                            const snax_simd_shape_t* out,
                            const snax_simd_op_t* ops, uint32_t n_ops);

// Launch the configured task; returns its id. Polls until the block has taken
// the configuration.
uint32_t snax_simd_launch(void);

// Launch without the confirm-poll. The block has a 2-deep task queue, so a kernel
// that stages the next task immediately overlaps its own CSR writes with the
// running task instead of serialising behind it. Wait on the finished counter.
uint32_t snax_simd_launch_async(void);

// Submit the staged task and return immediately -- no counter read at all.
//
// This is what lets the 2-entry taskQueue do its job. SimdTop snapshots the
// WHOLE task (both AGU configs, the extension enable mask and the operator
// CSRs) into the queue on the start pulse, so the core can arm and program task
// i+1 while task i is still running, and the CSR write itself back-pressures
// when the queue is full -- the core stalls on exactly the right cycle without
// polling. launch_async()'s discarded counter read is 5 cycles per call and
// launch()'s confirm-poll is worse; neither is needed when a batch is retired
// with snax_simd_wait_all().
void snax_simd_fire(void);

// Cumulative engine-busy cycles since reset, free-running.
//
// Use this, not snax_simd_last_task_cycle(), to measure a MULTI-task sequence:
// the per-task counters restart on every start pulse, so reading them forces a
// wait after each task and destroys the overlap.
__attribute__((always_inline)) static inline uint32_t snax_simd_busy_cycles(void) {
    return snax_read_simd_cfg_reg(SIMD_BUSY_CYCLES);
}

// MEASURED unit costs on this block, 64 accesses warm: a csrw is 1.0 cycle
// (posted -- ReqRspManager answers combinationally and snax_csr_mux_demux is
// pure always_comb), a csrr is 5.1 cycles, because the core stalls on the
// accelerator round trip until writeback. Reads are what cost; there is nothing
// to shave inside SNAX, so the lever is issuing fewer of them. Note in
// particular that launch_async() below reads the submitted-task counter back,
// which is 5 cycles a call if the caller discards it.
// The 1-D fast path: write ONLY the six CSRs that a 1-D task actually varies
// -- source base / bound / stride and destination base / bound / stride.
//
// Everything else in the AGU pair is invariant across such tasks: address
// high word (TCDM is 32-bit), spatial stride (always SIMD_LANE_BYTES),
// channel and byte masks (always all-ones), and temporal dimensions 1 and 2
// (always bound 1, stride 0, the neutral loop). Those are established by ONE
// snax_simd_program_fast() before the loop and then left alone.
//
// 6 CSR writes instead of 21. The caller is responsible for the invariant:
// every shape must come from snax_simd_shape_flat / _broadcast / _2d with a
// bound[1] of 1, and a full program must have run since the last task that
// violated it.
void snax_simd_program_1d(const snax_simd_shape_t* in,
                          const snax_simd_shape_t* out);


// Program a task from two shapes with nothing but CSR writes -- no validation,
// no branches, no calls. See the note in the .c: the checked entry point costs
// 313 cycles for 23 CSR writes because its 752-byte footprint misses in L1I,
// and this is what removes that. The shapes' unused dimensions must carry the
// neutral bound=1/stride=0 that the snax_simd_shape_* constructors install.
void snax_simd_program_fast(const snax_simd_shape_t* in,
                            const snax_simd_shape_t* out);

// Arm an operator with all-constant CSR addresses.
//
// snax_simd_enable_ext() has to walk SIMD_EXT_CUSTOM_CSR_NUM at run time to find
// the operator's CSR block, so every write it makes has a computed address and
// pays the jump-table dispatch. These macros take the generated
// SIMD_EXT_<NAME>_CSR base instead, so the whole arming is a handful of
// `csrw imm`. Use the arity that matches SIMD_EXT_<NAME>_CSR_NUM.
// Arm exactly one operator and disable every other, in a SINGLE csrw.
//
// The arm0 family below read-modify-writes the enable mask, and a read is 5
// cycles against a write's 1. But every call site here is
// `disable_all_ext(); arm<N>(...)`, whose combined effect on the mask is just
// `1 << id` -- a value that needs no reading to compute. These replace 1 write
// + 1 read + 1 write with 1 write.
#define snax_simd_use0(id) \
    snax_write_simd_cfg_reg(SIMD_EXT_ENABLE_PTR, 1u << (id))
#define snax_simd_use1(id, base, c0)               \
    do {                                           \
        snax_simd_use0(id);                        \
        snax_write_simd_cfg_reg((base) + 0, (c0)); \
    } while (0)
#define snax_simd_use2(id, base, c0, c1)           \
    do {                                           \
        snax_simd_use1(id, base, c0);              \
        snax_write_simd_cfg_reg((base) + 1, (c1)); \
    } while (0)
#define snax_simd_use3(id, base, c0, c1, c2)       \
    do {                                           \
        snax_simd_use2(id, base, c0, c1);          \
        snax_write_simd_cfg_reg((base) + 2, (c2)); \
    } while (0)

#define snax_simd_arm0(id)                                        \
    snax_write_simd_cfg_reg(SIMD_EXT_ENABLE_PTR,                  \
                            snax_read_simd_cfg_reg(SIMD_EXT_ENABLE_PTR) | (1u << (id)))
#define snax_simd_arm1(id, base, c0)          \
    do {                                      \
        snax_simd_arm0(id);                   \
        snax_write_simd_cfg_reg((base) + 0, (c0)); \
    } while (0)
#define snax_simd_arm2(id, base, c0, c1)      \
    do {                                      \
        snax_simd_arm1(id, base, c0);         \
        snax_write_simd_cfg_reg((base) + 1, (c1)); \
    } while (0)
#define snax_simd_arm3(id, base, c0, c1, c2)  \
    do {                                      \
        snax_simd_arm2(id, base, c0, c1);     \
        snax_write_simd_cfg_reg((base) + 2, (c2)); \
    } while (0)

// Write one operator CSR at a CONSTANT address. `base` must be a compile-time
// constant -- use the generated SIMD_EXT_<NAME>_CSR macros. This is the cheap way
// to change a coefficient between passes: one `csrw imm` rather than a
// jump-table dispatch.
#define snax_simd_set_op_csr(base, idx, val) \
    snax_write_simd_cfg_reg((base) + (idx), (val))

// Default budget for the checked wait below. This is a HANG detector, not a performance
// assertion, so it wants headroom rather than precision: the largest single task in this
// tree is a couple of thousand cycles of datapath, and 50k is ~30x that. It also wants to
// be SMALL enough that a kernel which hangs on its first pass and then runs nine more does
// not spend a million cycles discovering the same thing nine times -- which is why the
// kernels here also latch the failure and skip the rest. Define it before including this
// header to override (an app with genuinely long tasks should).
#ifndef SIMD_WAIT_BUDGET
#define SIMD_WAIT_BUDGET 50000u
#endif

// The same waits, with a CYCLE BUDGET. Return 0 if the task retired, 1 if the
// budget ran out.
//
// A task that never retires is not a rare event while a kernel is being written:
// mis-size a writer bound, or chain two operators whose beat ratios do not
// multiply out to it, and the writer waits for a beat the reader will never send.
// The unbounded waits above then spin forever, which in simulation means the run
// produces NOTHING -- no stage cycles, no checks, not even the printf that would
// say which pass it died in, because a kernel reports at the end and it never
// reaches the end. A bounded wait turns that into a normal failure: the caller
// names the pass and the run still exits.
//
// Budget generously. The point is to bound a HANG, not to catch a slow task, and
// the loop itself is slow -- a CSR read is ~5 cycles and snrt_mcycle() is not
// free -- so a budget near the real cost would fire on a healthy task.
static inline int snax_simd_wait_timeout(uint32_t task_id, uint32_t budget) {
    uint32_t t0 = snrt_mcycle();
    while (snax_read_simd_cfg_reg(SIMD_FINISHED_TASK_PTR) < task_id) {
        if ((uint32_t)(snrt_mcycle() - t0) > budget) return 1;
    }
    return 0;
}

static inline int snax_simd_wait_all_timeout(uint32_t budget) {
    return snax_simd_wait_timeout(snax_read_simd_cfg_reg(SIMD_SUBMITTED_TASK_PTR),
                                  budget);
}

// Block until the task with this id has retired -- OR until the budget runs out.
//
// There is deliberately no unbounded wait in this header. A task that never retires is a
// normal kind of mistake while a chain is being written (a mis-sized writer bound, an
// operator left armed from the previous pass, two operators whose beat ratios do not
// multiply out to it), and an unbounded spin turns that into a simulation that produces
// NOTHING and ends only when someone kills it. Bounded, the run says what happened and
// finishes; a caller that wants to ACT on it uses snax_simd_wait_all_checked() below,
// which returns the failure instead of only reporting it.
static inline void snax_simd_wait(uint32_t task_id) {
    if (snax_simd_wait_timeout(task_id, SIMD_WAIT_BUDGET))
        printf("[SIMD] HUNG: task %u did not retire in %u cycles (finished=%u)\n",
               task_id, SIMD_WAIT_BUDGET,
               snax_read_simd_cfg_reg(SIMD_FINISHED_TASK_PTR));
}

// Block until every submitted task has retired.
static inline void snax_simd_wait_all(void) {
    snax_simd_wait(snax_read_simd_cfg_reg(SIMD_SUBMITTED_TASK_PTR));
}

// Bounded wait + diagnostic: the shape every kernel actually wants.
//
// Returns 0 when the task retired. On timeout it names the pass, says how far the task
// counters got, and returns 1 so the caller can bail out instead of reading a buffer the
// block never wrote.
//
// WHY EVERY KERNEL SHOULD USE THIS. A task that never retires is a normal kind of mistake
// while a chain is being written -- mis-size a writer bound, leave an operator armed from
// the previous pass, or chain two whose beat ratios do not multiply out to it, and the
// writer waits for a beat the reader will never send. With an unbounded wait the run then
// produces NOTHING: no stage cycles, no checks, not even a line saying which pass died,
// because kernels report at the end and it never reaches the end. In simulation that also
// costs however long you are willing to wait before killing it. With this, the run ends in
// seconds and says where.
//
// `submitted` vs `finished` in the message separates the two failures worth telling apart:
// finished == submitted - 1 is one task stuck in the datapath, while a larger gap means
// tasks were queued behind it.
static inline int snax_simd_wait_all_checked(const char* what, uint32_t budget) {
    if (!snax_simd_wait_all_timeout(budget)) return 0;
    printf("[SIMD] HUNG: %s did not retire in %u cycles (submitted=%u finished=%u)\n",
           what, budget, snax_read_simd_cfg_reg(SIMD_SUBMITTED_TASK_PTR),
           snax_read_simd_cfg_reg(SIMD_FINISHED_TASK_PTR));
    return 1;
}

// configure + launch + wait. Returns 0 or the configure error.
int32_t snax_simd_run(const snax_simd_shape_t* in, const snax_simd_shape_t* out,
                      const snax_simd_op_t* ops, uint32_t n_ops);

// Re-point an already-configured task at new buffers and a new output beat
// count, keeping its geometry and operators. This is what a multi-pass chain
// uses between passes: five CSR writes instead of a full reprogram.
int32_t snax_simd_repoint(void* in_base, void* out_base, uint32_t out_beats);

// How many beats a chain emits for `in_beats` consumed. Covers the shapes this
// header models; a chain it cannot predict returns 0 and the caller must state
// the output shape itself.
uint32_t snax_simd_out_beats(const snax_simd_op_t* ops, uint32_t n_ops,
                             uint32_t in_beats);

// ============================================================== convenience

// Elementwise map over `beats` beats: out = func(a * x + b).
int32_t snax_simd_map(uint8_t ext, void* in, void* out, uint32_t beats,
                      uint32_t func, uint32_t a_bits, uint32_t b_bits);

// Row-wise reduction: `rows` rows of `beats_per_row`, one scalar beat per row.
int32_t snax_simd_reduce_rows(uint8_t ext, void* in, void* out, uint32_t rows,
                              uint32_t beats_per_row, uint32_t mode);

// Row-major transpose through the Transposer operator. `rows`/`cols` must be
// multiples of the tile width (8); `element_width_bits` is 8 or 16.
int32_t snax_simd_transpose(void* in, void* out, uint32_t rows, uint32_t cols,
                            uint32_t element_width_bits);

// A plain copy -- no operator, launched and waited for. Useful for moving a tile
// within TCDM without waking the DM core, and as the smoke test that the engine
// is alive. Note it CLEARS the operator chain, because that is what "copy"
// means; use snax_simd_program_flat() if you have already armed an operator.
int32_t snax_simd_copy(void* in, void* out, uint32_t bytes);

// Geometry only: sweep `beats` beats in and out, contiguous, leaving the
// operator chain exactly as it is. This is the shape-setting half of a task for
// kernels that manage their own operators.
int32_t snax_simd_program_flat(void* in, void* out, uint32_t beats);

// ============================================================== status

static inline uint32_t snax_simd_last_task_cycle(void) {
    return snax_read_simd_cfg_reg(SIMD_PERF_CTR_TASK);
}
static inline uint32_t snax_simd_last_read_cycle(void) {
    return snax_read_simd_cfg_reg(SIMD_PERF_CTR_READER);
}
static inline uint32_t snax_simd_last_write_cycle(void) {
    return snax_read_simd_cfg_reg(SIMD_PERF_CTR_WRITER);
}
static inline bool snax_simd_busy(void) {
    return (snax_read_simd_cfg_reg(SIMD_STATUS) & 0x1) != 0;
}

// Sticky since the last launch: a task was started whose AGU never became busy,
// i.e. the geometry was degenerate. The block drops such a task rather than
// hanging, so this bit is the only evidence it happened.
static inline bool snax_simd_bad_config(void) {
    return (snax_read_simd_cfg_reg(SIMD_STATUS) & 0x2) != 0;
}

