# Sizes only. This app measures nothing and checks nothing -- it asks which TASK fails to retire,
# and a task hangs or does not regardless of the values streaming through it. The input is written
# on-device as a constant FP16 bit pattern, so there is no array to generate and a shape rebuilds
# in about a second, which matters when you are bisecting across shapes.

import argparse
import hjson

FP16_PER_BEAT = 32


def main():
    p = argparse.ArgumentParser()
    p.add_argument("-c", "--cfg", required=True)
    args = p.parse_args()
    with open(args.cfg) as f:
        cfg = hjson.loads(f.read())
    rows, d = int(cfg["ROWS"]), int(cfg["D"])
    if d <= 0 or d % FP16_PER_BEAT != 0:
        raise ValueError(f"D must be a positive multiple of {FP16_PER_BEAT}, got {d}")
    if rows <= 0:
        raise ValueError(f"ROWS must be positive, got {rows}")
    print("// Generated by datagen.py -- sizes only, see the note there.")
    print("#pragma once")
    print(f"#define BSW_ROWS {rows}u")
    print(f"#define BSW_D {d}u")
    print(f"#define BSW_BEATS {d // FP16_PER_BEAT}u")


if __name__ == "__main__":
    main()
