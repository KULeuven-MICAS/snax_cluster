# Data for snax-versacore-few-row: one GEMM, D = X . W, laid out for VersaCore's two GEMM
# shapes, (16, 4, 16) and (8, 8, 16). Everything goes to DRAM as raw blobs:
#
#   fr_a<s>          X [m_max, K], INT8, A-layout of shape s: (Mu x Ku) blocks, m-major
#   fr_a3i           fr_a3 with each row block's K / Ku blocks in two interleaved halves: block k
#                    at 128 (k % H) + 64 (k / H), H = K / (2 Ku), so A advances 128 B a pass, as
#                    shape 3's INT8 B does
#   fr_b<s>_8        W8 [K, N], INT8, B-layout of shape s: (Ku x Nu) blocks, n-major
#   fr_b<s>_4        W4 [K, N], values in [-8, 7], the same B-layout nibble-packed: value 2i in
#                    the low nibble of byte i, which the B reader's converter widens back
#   fr_g<s>_<w>      X . W<w> [m_max, N], INT32, D-layout of shape s with N / Nu column blocks
#   fr_g<s>_<w>_n16  X . W<w>[:, :16] [m_max, Nu], INT32, the same with one column block
#
# for s in {0, 3}: the cfg's shape 0 and whichever index the cfg gives (8, 8, 16). A task of
# M <= m_max rows runs ceil(M / Mu) row blocks and writes the prefix of its golden's layout,
# since every layout is m-major: the rows past M in the last block are real rows of X, so the
# prefix matches word for word.

import argparse
import os
import sys

import hjson
import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "../../dsv2"))  # the util package
from util.emit import Emitter  # noqa E402
from util.layout import pack_int4, to_a, to_b, to_d  # noqa E402

GEMM = (16, 4, 16)
FEW = (8, 8, 16)


def shapes_from_hwcfg(hw):
    """Indices of the (16, 4, 16) and (8, 8, 16) array shapes in the cfg's one data type."""
    acc = hw["snax_versacore_core_template"]["snax_acc_cfg"][0]
    unrolling = [tuple(int(v) for v in s) for s in acc["snax_versacore_spatial_unrolling"][0]]
    if unrolling[0] != GEMM:
        raise ValueError(f"array shape 0 is {unrolling[0]}, not {GEMM}")
    if FEW not in unrolling:
        raise ValueError(f"the cfg declares no {FEW} array shape: {unrolling}")
    return 0, unrolling.index(FEW)


def a_halves(a, kt, blk):
    """Each row block's kt A blocks (blk bytes) reordered so block k sits at slot 2 (k % H) +
    k / H, H = kt / 2: the first half of K on the even slots, the second on the odd ones."""
    h = kt // 2
    b = a.reshape(-1, 2, h, blk)            # [row block][half][k % H][byte]
    return np.ascontiguousarray(b.transpose(0, 2, 1, 3)).reshape(-1)


def main():
    p = argparse.ArgumentParser(description="Data for snax-versacore-few-row")
    p.add_argument("--swcfg", required=True)
    p.add_argument("--hwcfg", required=True)
    p.add_argument("--header", required=True)
    p.add_argument("--blob-dir", required=True)
    args = p.parse_args()
    with open(args.swcfg) as f:
        sw = hjson.load(f)
    with open(args.hwcfg) as f:
        hw = hjson.load(f)

    K, N, m_max = int(sw["K"]), int(sw["N"]), int(sw["m_max"])
    s_gemm, s_few = shapes_from_hwcfg(hw)
    for mu, ku, nu in (GEMM, FEW):
        assert K % ku == 0 and N % nu == 0 and m_max % mu == 0
    rng = np.random.default_rng(int(sw["seed"]))
    X = rng.integers(-128, 128, size=(m_max, K), dtype=np.int64).astype(np.int8)
    W = {8: rng.integers(-128, 128, size=(K, N), dtype=np.int64).astype(np.int8),
         4: rng.integers(-8, 8, size=(K, N), dtype=np.int64).astype(np.int8)}

    e = Emitter(args.blob_dir)
    e.c("// Generated by snax-versacore-few-row/data/datagen.py. Do not edit.")
    e.define("FR_K", K)
    e.define("FR_N", N)
    e.define("FR_NU", 16)
    e.define("FR_M_MAX", m_max)
    e.define("FR_SHAPE_GEMM", s_gemm, "(16, 4, 16)")
    e.define("FR_SHAPE_FEW", s_few, "(8, 8, 16)")
    for tag, mesh in (("0", GEMM), ("3", FEW)):
        e.blob(f"fr_a{tag}", to_a(X, mesh))
        e.blob(f"fr_b{tag}_8", to_b(W[8], mesh))
        e.blob(f"fr_b{tag}_4", pack_int4(to_b(W[4], mesh)))
        for w in (8, 4):
            D = X.astype(np.int64) @ W[w].astype(np.int64)
            assert np.all(np.abs(2 * D) < 2**31)  # the C pass accumulates D twice
            D = D.astype(np.int32)
            e.blob(f"fr_g{tag}_{w}", to_d(D, mesh))
            e.blob(f"fr_g{tag}_{w}_n16", to_d(np.ascontiguousarray(D[:, :16]), mesh))
    e.blob("fr_a3i", a_halves(to_a(X, FEW), K // FEW[1], FEW[0] * FEW[1]))
    e.write(args.header, os.path.join(args.blob_dir, "blobs.S"))


if __name__ == "__main__":
    main()
