"""data.h for snax-xdma-crest-decompress: per case, the compressed stream and the weights as stored,
both from the reference codec (hw/chisel/doc/crest_decompressor/crest_codec.py)."""

import argparse
import os
import sys

import hjson
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "../../../../../../hw/chisel/doc/crest_decompressor"))
import crest_codec  # noqa: E402

MODE_NAME = {0: "nib", 1: "byte", 2: "bf16"}


def c_array(name, data):
    words = np.frombuffer(bytes(data), dtype="<u4")
    body = ",\n".join(
        "    " + ", ".join(f"0x{w:08x}" for w in words[i:i + 8]) for i in range(0, len(words), 8))
    return (f"static const uint32_t {name}[{len(words)}] __attribute__((aligned(64))) = {{\n"
            f"{body}\n}};\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-c", "--cfg", required=True)
    cfg = hjson.loads(open(ap.parse_args().cfg).read())
    out = ["// Generated by datagen.py from crest_codec.py -- do not edit.",
           "#pragma once", "#include <stdint.h>", ""]
    rows, max_in, max_out = [], 0, 0
    seed = cfg.get("seed", 0)
    for name in cfg["cases"]:
        try:
            payload, mode, params = crest_codec.case(name, np.random.default_rng(seed))
        except FileNotFoundError:
            print(f"datagen: {name} skipped, not in CREST_WEIGHT_CACHE", file=sys.stderr)
            continue
        payload = np.frombuffer(bytes(payload), np.uint8)[:cfg["max_beats"] * 64]
        words, info = crest_codec.encode(payload, mode, params)
        beats = payload.size // 64
        if not np.array_equal(crest_codec.decode(words, beats), payload):
            raise SystemExit(f"{name}: the reference codec does not round-trip")
        k = len(rows)
        in_words = words.size // 64
        out.append(c_array(f"crest_in_{k}", words))
        out.append(c_array(f"crest_out_{k}", payload))
        m = MODE_NAME[crest_codec.MODES.get(mode, mode)]
        rows.append(f'    {{"{name}", "{m}", crest_in_{k}, crest_out_{k}, {in_words}, {beats}, '
                    f'{info["t1"]}, {info["t2"]}, {info["raw_groups"]}}},')
        max_in, max_out = max(max_in, in_words), max(max_out, beats)
    out += ["typedef struct {",
            "    const char *name;",
            "    const char *mode;     // nib, byte or bf16",
            "    const uint32_t *in;   // compressed stream, 64 B words",
            "    const uint32_t *out;  // the weights as stored, 64 B beats",
            "    uint32_t in_words;",
            "    uint32_t out_beats;",
            "    uint32_t tier1;",
            "    uint32_t tier2;",
            "    uint32_t raw_groups;",
            "} crest_case_t;", "",
            f"#define CREST_NUM_CASES {len(rows)}",
            f"#define CREST_MAX_IN_WORDS {max_in}",
            f"#define CREST_MAX_OUT_BEATS {max_out}", "",
            "static const crest_case_t crest_cases[CREST_NUM_CASES] = {", *rows, "};"]
    print("\n".join(out))


if __name__ == "__main__":
    main()
