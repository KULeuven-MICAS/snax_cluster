"""Writes data.h for snax-dma-transpose: the N x N matrices the DMA transposes.

    python3 data/datagen.py > data/data.h

a8_l2 holds int8 elements, a64_l2 int64 ones, both row-major, as raw bytes and words (a copy
does not read them as numbers). The values are random with Python's seed 0, so data.h is the
same on every run.
"""

import random

N = 64


def array(name: str, ctype: str, digits: int, values: list[int]) -> str:
    rows = []
    for i in range(0, len(values), 8):
        rows.append(", ".join(f"0x{v:0{digits}x}" for v in values[i:i + 8]))
    body = ",\n    ".join(rows)
    return f"{ctype} {name}[N * N] __attribute__((aligned(64))) = {{\n    {body}\n}};\n"


def main() -> None:
    rng = random.Random(0)
    a8 = [rng.getrandbits(8) for _ in range(N * N)]
    a64 = [rng.getrandbits(64) for _ in range(N * N)]
    print("// Generated by data/datagen.py (seed 0). Do not edit.")
    print()
    print("#include <stdint.h>")
    print()
    print(f"#define N {N}")
    print()
    print("// In .data, which base.ld places in DRAM (the program's L2).")
    print(array("a8_l2", "uint8_t", 2, a8))
    print(array("a64_l2", "uint64_t", 16, a64), end="")


if __name__ == "__main__":
    main()
