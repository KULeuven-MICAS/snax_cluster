# Sizes only. This app measures TIME, not numbers: the kernels it runs are the ones
# snax-simd-{silu,swiglu,softmax-multirow,rmsnorm-multirow,reduce-multirow} already check for
# numerical correctness, and re-checking them here would only add a second place to keep a golden
# in agreement. The input is written on-device as a constant FP16 bit pattern, so there is no
# array to generate and a sweep point rebuilds in about a second.
#
# A row is D / lanes SIMD beats, the lane count (simd_fp16_lanes) read from the hardware cfg.

import argparse
import os
import sys

import hjson

sys.path.append(os.path.join(os.path.dirname(__file__), "../../../../../../util/sim/"))
from snax_utils import simd_fp16_lanes  # noqa E402


def main():
    p = argparse.ArgumentParser()
    p.add_argument("-c", "--cfg", required=True)
    p.add_argument("--hwcfg", required=True, help="cluster hardware cfg (sets the SIMD lane count)")
    args = p.parse_args()
    with open(args.cfg) as f:
        cfg = hjson.loads(f.read())
    with open(args.hwcfg) as f:
        lanes = simd_fp16_lanes(hjson.loads(f.read()))
    rows, d = int(cfg["ROWS"]), int(cfg["D"])
    if d <= 0 or d % lanes != 0:
        raise ValueError(f"D must be a positive multiple of the {lanes} SIMD lanes, got {d}")
    if rows <= 0:
        raise ValueError(f"ROWS must be positive, got {rows}")
    print("// Generated by datagen.py -- sizes only, see the note there.")
    print("#pragma once")
    print(f"#define BSW_ROWS {rows}u")
    print(f"#define BSW_D {d}u")
    print(f"#define BSW_BEATS {d // lanes}u")


if __name__ == "__main__":
    main()
