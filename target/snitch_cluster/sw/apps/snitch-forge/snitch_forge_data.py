"""What every snitch-forge datagen.py shares: the types, the arguments, the
generator, forge's draw and the writing of data.h.

A kernel's datagen.py parses its sizes with ``parse``, draws its inputs with
``draw`` from ``generator`` (forge's range per kernel, or with --range full
uniform over the whole type), computes its golden output with numpy at
``args.acc_t`` (so it wraps as the C does) and prints data.h with ``write``.
data.h holds the typedefs in_t (the inputs) and acc_t (the op and the
outputs), the sizes as SF_<NAME> defines, the scalars (acc_t, not const, so
the program loads them at run time as forge's accelerators read them from a
CSR), the inputs, each array updated in place with its <name>_golden, and each
output and its <name>_golden.
"""

import argparse
import os
import sys

import numpy as np

sys.path.append(os.path.join(os.path.dirname(__file__), "../../../../../util/sim/"))
from data_utils import format_vector_declaration, format_vector_definition  # noqa: E402

# TYPE: (in_t, acc_t). int64 and the presets i32, i16 and i8 are forge's
# (snax-forge kernels/README.md); int32 is the cores' native width.
TYPES = {
    "int64": (np.int64, np.int64),
    "i32": (np.int32, np.int64),
    "i16": (np.int16, np.int32),
    "i8": (np.int8, np.int32),
    "int32": (np.int32, np.int32),
}

C_TYPES = {np.int64: "int64_t", np.int32: "int32_t", np.int16: "int16_t", np.int8: "int8_t"}

# Every array starts on a DMA beat
ALIGNMENT = 64

# A size must split into whole 64-bit words at the narrowest type
SIZE_MULTIPLE = 8

# --range: forge's range per kernel (draw's low and high), or full: uniform over
# the whole type, drawn as uniform int64 and cast, so every narrower type gets
# its low bits, as uniform; sums and products then wrap, in the golden as in
# the C
RANGES = ("forge", "full")
_range = "forge"


def parse(kernel, sizes):
    """The command line: one --<size> per name in ``sizes`` (upper case, as
    data/Makefile passes them), --type and --seed. Adds in_t and acc_t."""
    parser = argparse.ArgumentParser(description=f"{kernel}'s data.h, printed to stdout")
    for name in sizes:
        parser.add_argument(f"--{name.lower()}", dest=name, type=int, required=True)
    parser.add_argument("--type", required=True, choices=sorted(TYPES))
    parser.add_argument("--seed", required=True, help="an integer, or random for fresh data")
    parser.add_argument("--range", default="forge", choices=RANGES,
                        help="forge's range per kernel (default), or full: uniform over the type")
    args = parser.parse_args()
    for name in sizes:
        v = getattr(args, name)
        if v <= 0 or v % SIZE_MULTIPLE:
            parser.error(f"{name} = {v}: give a positive multiple of {SIZE_MULTIPLE}")
    if args.seed != "random" and not args.seed.isdigit():
        parser.error(f"--seed {args.seed}: give a non-negative integer or random")
    args.sizes = list(sizes)
    args.in_t, args.acc_t = TYPES[args.type]
    global _range
    _range = args.range
    return args


def generator(seed):
    """numpy's default_rng at ``seed``, as forge's make_inputs gets it, and the
    seed used: SEED=random draws one, so data.h can name it."""
    if seed == "random":
        seed = int(np.random.SeedSequence().entropy % (1 << 32))
    seed = int(seed)
    return np.random.default_rng(seed), seed


def draw(rng, n, to_t, low=-1000, high=1000, dtype=np.int64):
    """forge's draw: n values from rng.integers(low, high, dtype=dtype), the
    high end excluded, then cast to to_t, wrapping where to_t is narrower
    (forge's kernel_inputs casts each input to its container's type the same
    way). dtype is the one the kernel's make_inputs draws at: numpy gives other
    values for the same seed at int32 than at int64. With --range full, low,
    high and dtype are set aside: n uniform int64 values, cast to to_t."""
    if _range == "full":
        i = np.iinfo(np.int64)
        return rng.integers(i.min, i.max, endpoint=True, size=n, dtype=np.int64).astype(to_t)
    return rng.integers(low, high, size=n, dtype=dtype).astype(to_t)


def write(kernel, args, seed, inputs, outputs, inouts=None, scalars=None):
    """Print data.h: the typedefs, the sizes, the scalars, each input (const),
    each array updated in place (inouts: name to (initial values, golden), at
    acc_t), each output (zeroed at load) and its golden."""
    sizes = " ".join(f"{name}={getattr(args, name)}" for name in args.sizes)
    lines = [
        f"// {kernel}'s data, generated by datagen.py: {sizes}, TYPE={args.type}, seed {seed}"
        + (" (SEED=random)" if args.seed == "random" else "")
        + (", full range" if args.range == "full" else ""),
        "",
        "#include <stdint.h>",
        "",
        f"typedef {C_TYPES[args.in_t]} in_t;",
        f"typedef {C_TYPES[args.acc_t]} acc_t;",
        "",
    ]
    lines += [f"#define SF_{name} {getattr(args, name)}" for name in args.sizes]
    lines += [f'#define SF_TYPE "{args.type}"', f'#define SF_SIZE "{sizes}"']
    lines += [f'#define SF_RANGE "{args.range}"', ""]
    for name, v in (scalars or {}).items():
        lines += [f"acc_t {name} = {int(v)};", ""]
    for name, arr in inputs.items():
        lines += [format_vector_definition("const in_t", name, arr, alignment=ALIGNMENT), ""]
    for name, (init, golden) in (inouts or {}).items():
        lines += [format_vector_definition("acc_t", name, init, alignment=ALIGNMENT), ""]
        lines += [format_vector_definition("const acc_t", f"{name}_golden", golden), ""]
    for name, arr in outputs.items():
        lines += [format_vector_declaration("acc_t", name, arr, alignment=ALIGNMENT), ""]
        lines += [format_vector_definition("const acc_t", f"{name}_golden", arr), ""]
    print("\n".join(lines))
