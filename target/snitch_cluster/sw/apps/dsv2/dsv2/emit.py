"""data.h plus binary blobs for the snax-dsv2-* apps.

A layer's weights are tens of MiB: as C initialisers they would be hundreds of MB of
source. So every array goes out as raw bytes, linked into DRAM by an assembly file of
`.incbin` directives, and data.h only declares it:

    data.h     #define constants, extern declarations, any C the app wants verbatim
    blobs.S    .section .rodata.dsv2 ; .balign 64 ; <name>: .incbin "<abs>/<name>.bin"

.rodata is placed in L3 (DRAM) by the linker script, which is where the iDMA streams
from. A blob the kernel WRITES (a KV cache) goes to .data.dsv2 instead, also in L3, and is
declared without const. Every blob starts 64-byte aligned, one beat.
"""

import os

import numpy as np

_CTYPE = {np.dtype(np.int8): "int8_t", np.dtype(np.uint8): "uint8_t",
          np.dtype(np.int16): "int16_t", np.dtype(np.uint16): "uint16_t",
          np.dtype(np.int32): "int32_t", np.dtype(np.uint32): "uint32_t"}


class Emitter:
    def __init__(self, blob_dir):
        self.blob_dir = os.path.abspath(blob_dir)
        self._h = []
        self._s = {".rodata.dsv2": [], ".data.dsv2": []}
        self.bytes = 0
        os.makedirs(self.blob_dir, exist_ok=True)

    def define(self, name, value, comment=None):
        c = f"  // {comment}" if comment else ""
        self._h.append(f"#define {name} {value}{c}")

    def c(self, text):
        self._h.append(text)

    def blob(self, name, arr, writable=False):
        """Link `arr` (little-endian, its dtype decides the C type) as `name` in DRAM."""
        a = np.ascontiguousarray(arr)
        if a.dtype == np.float16:
            a = a.view(np.uint16)
        ctype = _CTYPE[a.dtype]
        path = os.path.join(self.blob_dir, f"{name}.bin")
        a.astype(a.dtype.newbyteorder("<"), copy=False).tofile(path)
        const = "" if writable else "const "
        self._h.append(f"extern {const}{ctype} {name}[{a.size}];")
        self._s[".data.dsv2" if writable else ".rodata.dsv2"] += [
            "    .balign 64", f"    .globl {name}", f"{name}:", f'    .incbin "{path}"']
        self.bytes += a.nbytes
        return name

    def header(self):
        return "\n".join(["// Generated by a dsv2 datagen. Do not edit.", "#pragma once",
                          "#include <stdint.h>", ""] + self._h) + "\n"

    def asm(self):
        out = ["// Generated by a dsv2 datagen. Do not edit."]
        for sec, flags in ((".rodata.dsv2", "a"), (".data.dsv2", "aw")):
            if self._s[sec]:
                out += [f'    .section {sec}, "{flags}"'] + self._s[sec]
        return "\n".join(out) + "\n"

    def write(self, header_path, asm_path):
        with open(header_path, "w") as f:
            f.write(self.header())
        with open(asm_path, "w") as f:
            f.write(self.asm())
